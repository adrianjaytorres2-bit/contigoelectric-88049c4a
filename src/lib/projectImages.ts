// Get all images for a project (returns array)
export const getProjectImages = (type: string, name: string, city?: string): string[] => {
  const nameLower = name.toLowerCase();
  
  // Check for multi-image projects first
  for (const [key, images] of Object.entries(projectMultiImageMap)) {
    if (nameLower.includes(key)) {
      return images;
    }
  }
  
  // Return single image as array
  return [getProjectImage(type, name, city)];
};

// Get project image based on name and type
export const getProjectImage = (type: string, name: string, city?: string): string => {
  const nameLower = name.toLowerCase();
  const cityLower = city?.toLowerCase() || "";
  
  // Try to find exact or partial match in the map
  for (const [key, image] of Object.entries(projectImageMap)) {
    if (nameLower.includes(key)) {
      // Special handling for location-specific projects
      if (key === "regions" && cityLower.includes("kissimmee")) {
        return regionsBankKissimmee;
      }
      if (key === "regions" && cityLower.includes("lake nona")) {
        return regionsBankLakeNona;
      }
      if (key === "tropical smoothie" && cityLower.includes("bradenton")) {
        return tropicalSmoothieBradenton;
      }
      if (key === "7-eleven" && cityLower.includes("davenport")) {
        return sevenElevenDavenport;
      }
      if (key === "7-eleven" && cityLower.includes("sebastian")) {
        return sevenElevenSebastian;
      }
      return image;
    }
  }
  
  // Fallback to category-based images
  if (type === "Luxury Retail") {
    return projectGucci;
  }
  if (type === "Restaurant" || type === "Fitness" || type === "Wellness") {
    return projectRestaurant;
  }
  if (type === "Retail") {
    return projectRetail;
  }
  if (type === "Commercial" || type === "Financial" || type === "Medical" || type === "Multi-Family" || type === "Government" || type === "Education") {
    return projectCommercial;
  }
  
  return projectElectrical;
};

